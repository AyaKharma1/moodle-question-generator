def _fold(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "").casefold()).strip()


def _plain(html_text: str) -> str:
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", html_text or ""))).strip()


def _xml_text(raw_xml: str) -> str:
    parser = etree.XMLParser(resolve_entities=False, no_network=True, load_dtd=False)
    try:
        el = etree.fromstring(raw_xml.encode("utf-8"), parser=parser)
    except etree.XMLSyntaxError:
        return ""
    return " ".join(p for p in (_plain(t.text or "") for t in el.iter("text")) if p)


